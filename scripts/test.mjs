import {spawnSync} from 'node:child_process';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {runPython} from './python.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
await mkdir(new URL('../evidence/studio-v1/',import.meta.url),{recursive:true});
await mkdir(new URL('../evidence/compose-v1/',import.meta.url),{recursive:true});
const selected=JSON.parse(await readFile(new URL('test-files.json',import.meta.url),'utf8'));
const env={...process.env,PYTHONUTF8:'1',PYTHONDONTWRITEBYTECODE:'1'};
const js=spawnSync(process.execPath,['--test',...selected.javascript],{cwd:root,env,encoding:'utf8'});
if(js.error)throw js.error;
const python=runPython(['-B','-m','unittest','discover','-s','tests','-p','test_*.py'],{cwd:root});
const jsPassed=Number(js.stdout.match(/^# pass (\d+)/m)?.[1]??0),jsFailed=Number(js.stdout.match(/^# fail (\d+)/m)?.[1]??1);
const pyCount=Number((python.stdout+python.stderr).match(/Ran (\d+) tests?/)?.[1]??0);
const report={javascript:{exit:js.status,passed:jsPassed,failed:jsFailed,files:selected.javascript},python:{exit:python.status,tests:pyCount,files:selected.python},ok:js.status===0&&python.status===0};
await writeFile(new URL('../evidence/test-results.json',import.meta.url),JSON.stringify(report,null,2)+'\n');
if(js.status!==0)process.stdout.write(js.stdout+js.stderr);
if(python.status!==0)process.stdout.write(python.stdout+python.stderr);
console.log(JSON.stringify(report,null,2));
if(!report.ok)process.exitCode=1;
